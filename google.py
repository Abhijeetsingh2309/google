    "def call_llm(system_prompt, user_prompt, model=MODEL, max_tokens=600):\n",
    "    resp = openai.ChatCompletion.create(\n",
    "        model=model,\n",
    "        messages=[\n",
    "            {\"role\":\"system\",\"content\":system_prompt},\n",
    "            {\"role\":\"user\",\"content\":user_prompt}\n",
    "        ],\n",
    "        max_tokens=max_tokens,\n",
    "        temperature=0.2\n",
    "    )\n",
    "    return resp[\"choices\"][0][\"message\"][\"content\"].strip()\n",
    "\n",
    "SYSTEM_PROMPT = \"\"\"You are a helpful student productivity assistant. Produce concise, structured JSON\n",
    "when asked to output schedules, subtasks, or study routines. Keep tone encouraging but direct.\"\"\""
