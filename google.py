    "        parsed = json.loads(llm_out)\n",
    "    except:\n",
    "        parsed = {\"llm_text\": llm_out}\n",
    "    \n",
    "    return {\n",
    "        \"prioritized_tasks\": prioritized,\n",
    "        \"daily_plan\": daily_plan,\n",
    "        \"subtasks\": subtasks,\n",
    "        \"llm_recommendation\": parsed\n",
    "    }"
