    "# Cell B: Utility functions\n",
    "def parse_tasks(task_list):\n",
    "    \"\"\"\n",
    "    task_list: list of dicts: {\"title\": str, \"deadline\": \"YYYY-MM-DD\", \"estimate_hours\": float, \"priority\": optional int}\n",
    "    Return normalized list with deadline datetime.\n",
    "    \"\"\"\n",
    "    normalized = []\n",
    "    for t in task_list:\n",
    "        d = t.get(\"deadline\")\n",
    "        try:\n",
    "            dd = datetime.fromisoformat(d) if d else None\n",
    "        except:\n",
    "            dd = None\n",
    "        normalized.append({\n",
    "            \"title\": t[\"title\"],\n",
    "            \"deadline\": dd,\n",
    "            \"estimate_hours\": float(t.get(\"estimate_hours\", 1)),\n",
    "            \"priority\": int(t.get(\"priority\", 2))  # 1-high,2-medium,3-low\n",
    "        })\n",
    "    return normalized\n",
    "\n",
    "def score_task(task, today=None):\n",
    "    \"\"\"\n",
    "    Simple heuristic score: lower score => do earlier\n",
    "    score = days_left / priority_weight / estimate_hours\n",
    "    \"\"\"\n",
    "    if today is None:\n",
    "        today = datetime.now()\n",
    "    if task[\"deadline\"] is None:\n",
    "        days_left = 999\n",
    "    else:\n",
    "        days_left = max(1, (task[\"deadline\"] - today).days)\n",
    "    priority_weight = {1: 0.6, 2: 1.0, 3: 1.5}[task[\"priority\"]]\n",
    "    return days_left * priority_weight * task[\"estimate_hours\"]\n",
    "\n",
    "def prioritize(tasks):\n",
    "    tasks_with_score = []\n",
    "    for t in tasks:\n",
    "        t2 = t.copy()\n",
    "        t2[\"score\"] = score_task(t)\n",
    "        tasks_with_score.append(t2)\n",
    "    tasks_sorted = sorted(tasks_with_score, key=lambda x: x[\"score\"])\n",
    "    return tasks_sorted\n",
    "\n",
    "def split_task_into_subtasks(title, hours):\n",
    "    \"\"\"\n",
    "    Heuristic split: convert estimate hours into chunks (50-90 min study sessions)\n",
    "    \"\"\"\n",
    "    chunk = 1.5  # hours per study chunk\n",
    "    num = max(1, int((hours + 0.49) // chunk))\n",
    "    subtasks = [f\"{title} — Study session {i+1}/{num} (~{round(hours/num,2)} hrs)\" for i in range(num)]\n",
    "    return subtasks\n",
    "\n",
    "def generate_daily_plan(prioritized_tasks, daily_hours_available):\n",
    "    \"\"\"\n",
    "    Distribute tasks into days, greedily fill daily_hours_available\n",
    "    Returns dict mapping date->list of (title, hours)\n",
    "    \"\"\"\n",
    "    plan = {}\n",
    "    today = datetime.now().date()\n",
    "    day = 0\n",
    "    remaining = []\n",
    "    for t in prioritized_tasks:\n",
    "        remaining.append({\"title\": t[\"title\"], \"hours\": t[\"estimate_hours\"], \"deadline\": t[\"deadline\"]})\n",
    "\n",
    "    while remaining and day < 30:  # stop after 30 days fallback\n",
    "        date = today + timedelta(days=day)\n",
    "        cap = daily_hours_available\n",
    "        plan.setdefault(date.isoformat(), [])\n",
    "        i = 0\n",
    "        while i < len(remaining) and cap > 0:\n",
    "            item = remaining[i]\n",
    "            if item[\"hours\"] <= cap:\n",
    "                plan[date.isoformat()].append({\"title\": item[\"title\"], \"hours\": item[\"hours\"]})\n",
    "                cap -= item[\"hours\"]\n",
    "                remaining.pop(i)\n",
    "            else:\n",
    "                plan[date.isoformat()].append({\"title\": item[\"title\"], \"hours\": cap})\n",
    "                item[\"hours\"] -= cap\n",
    "                cap = 0\n",
    "                i += 1\n",
    "        day += 1\n",
    "    return plan"
